"""
build_bank.py — merge data/json/<tech>.<batch>.json into app/questions.js (window.QBANK).

    python3 tools/build_bank.py            # all technologies
    python3 tools/build_bank.py --example  # only the docs example (for UI smoke tests)
"""
import glob
import json
import os
import subprocess
import sys
from collections import Counter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
from qb import TECHS, DIFFS  # noqa: E402

OUT = os.path.join(ROOT, "app", "questions.js")


def main():
    example = "--example" in sys.argv
    if example:
        subprocess.run([sys.executable, os.path.join(ROOT, "docs", "example_batch.py")], check=True)
        files = [os.path.join(ROOT, "data", "json", "javascript.example.json")]
    else:
        files = sorted(f for f in glob.glob(os.path.join(ROOT, "data", "json", "*.json")) if ".example." not in f)
    questions = []
    for f in files:
        with open(f, encoding="utf-8") as fh:
            questions.extend(json.load(fh))
    order = {t: i for i, t in enumerate(TECHS)}

    def key(q):
        last = q["id"].split("-")[-1]
        num = "".join(ch for ch in last if ch.isdigit())
        # quick-recall ids (e.g. js-q01) sort after the main bank of their technology
        return (order.get(q["technology"], 99), 1 if last.startswith("q") else 0, int(num) if num else 0, q["id"])

    questions.sort(key=key)
    ids = Counter(q["id"] for q in questions)
    dups = [i for i, n in ids.items() if n > 1]
    if dups:
        sys.exit(f"Duplicate ids: {dups}")
    for q in questions:
        q.pop("_file", None)
        if not q.get("documentationUrl") and q.get("references"):
            q["documentationUrl"] = q["references"][0]["url"]
    by_tech = Counter(q["technology"] for q in questions)
    by_diff = Counter(q["difficulty"] for q in questions)
    header = (
        "/* Interview Prep BD — bilingual question bank (English + বাংলা).\n"
        f" * {len(questions)} questions across {len(by_tech)} categories. Versions verified 2026-10-12 (Node.js labels 2026-10-26).\n"
        " * Generated by tools/build_bank.py from data/src/*.py — edit the sources, not this file.\n"
        " * Schema: id, technology, subtopic, difficulty, type, market, priority, estimatedMinutes, tags,\n"
        " *   technologyVersion, verifiedAt, versionSensitive, status, documentationUrl, question{en,bn},\n"
        " *   answer{en,bn}, explanation{en,bn}, interviewTip{en,bn}, commonMistakes?, code?{language,source,output?},\n"
        " *   setup?, extraCode?[], followUps[{en,bn}], related[], references[{title,url}],\n"
        " *   options?[{en,bn}] + correctIndex (MCQ), complexity?{time,space}, quickAnswer?{en,bn}\n"
        " */\n"
    )
    body = "window.QBANK = [\n" + ",\n".join(json.dumps(q, ensure_ascii=False, separators=(",", ":")) for q in questions) + "\n];\n"
    if example:
        out = OUT
        os.remove(files[0])
    else:
        out = OUT
    with open(out, "w", encoding="utf-8") as fh:
        fh.write(header + body)
    print(f"Wrote {os.path.relpath(out, ROOT)}: {len(questions)} questions, {os.path.getsize(out)/1024:.0f} KB")
    for t in TECHS:
        print(f"  {t:12s} {by_tech.get(t, 0):3d}")
    print("  by difficulty:", {d: by_diff.get(d, 0) for d in DIFFS})


if __name__ == "__main__":
    main()
